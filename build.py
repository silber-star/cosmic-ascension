#!/usr/bin/env python3
"""COSMIC ASCENSION — deploy build. Python 3 stdlib only, no npm.

    python3 build.py            # tests → dist/ + cosmic-ascension.zip
    python3 build.py --no-test  # skip the jsc tests

What it makes:
  dist/index.html   index.html with the <script src> list swapped for one game.js
  dist/game.js      every script from index.html, concatenated in the same order
  dist/style.css    css/style.css
  cosmic-ascension.zip   dist/ zipped with index.html at the root (itch.io upload)
  cosmic-ascension.html  the whole game in one file, to send to someone: double-click to play

game.js and style.css are linked with ?v=<content hash>, so a browser never keeps an
old copy after a redeploy. Files are overwritten, never deleted: the output names are
fixed, so nothing stale piles up in dist/.
"""
import datetime
import hashlib
import pathlib
import re
import subprocess
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent
DIST = ROOT / 'dist'
ZIP = ROOT / 'cosmic-ascension.zip'
SINGLE = ROOT / 'cosmic-ascension.html'
JSC = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/A/Helpers/jsc'
SCRIPT_TAG = re.compile(r'[ \t]*<script src="([^"]+)"></script>\n')
CSS_LINK = 'href="css/style.css"'


def fail(msg):
    sys.exit('✗ build stopped: ' + msg)


def run_tests():
    if not pathlib.Path(JSC).exists():
        fail('jsc not found — run with --no-test to skip the tests')
    r = subprocess.run([JSC, 'tests/run.js'], cwd=ROOT, capture_output=True, text=True)
    last = (r.stdout.strip().splitlines() or ['(no output)'])[-1]
    m = re.search(r'(\d+) passed, (\d+) failed', last)
    if r.returncode or not m or m.group(2) != '0':
        print(r.stdout + r.stderr)
        fail('tests: ' + last)
    print('✓ tests: ' + last.lstrip('✓ '))


def bundle(html):
    tags = list(SCRIPT_TAG.finditer(html))
    if not tags:
        fail('no <script src> tags in index.html')
    for a, b in zip(tags, tags[1:]):
        if a.end() != b.start():
            fail('the <script src> tags in index.html must sit together in one block')
    parts = []
    for m in tags:
        src = ROOT / m.group(1)
        if not src.is_file():
            fail('missing script ' + m.group(1))
        # the ';' keeps one file's last expression from running into the next file
        parts.append('/* ── %s ── */\n%s\n;\n' % (m.group(1), src.read_text('utf-8').rstrip()))
    return tags, ''.join(parts)


def single_file(page, js, css, ver):
    # these strings would end the inline block early and break the page
    if '</script' in js.lower() or '<!--' in js:
        fail('game.js contains </script or <!--, which cannot be inlined')
    if '</style' in css.lower():
        fail('style.css contains </style, which cannot be inlined')
    link = '<link rel="stylesheet" href="style.css?v=%s">' % ver
    script = '<script src="game.js?v=%s"></script>' % ver
    if link not in page or script not in page:
        fail('could not find the css and js tags to inline')
    return page.replace(link, '<style>\n' + css + '</style>').replace(script, '<script>\n' + js + '</script>')


def main():
    if '--no-test' not in sys.argv:
        run_tests()
    html = (ROOT / 'index.html').read_text('utf-8')
    css = (ROOT / 'css' / 'style.css').read_text('utf-8')
    if CSS_LINK not in html:
        fail('index.html no longer links css/style.css')
    tags, js = bundle(html)
    ver = hashlib.sha1((js + css).encode('utf-8')).hexdigest()[:8]
    stamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
    js = ('/* COSMIC ASCENSION build %s (%s). Generated by build.py from the scripts in index.html: '
          'edit those, not this file. */\n' % (ver, stamp)) + js
    out = (html[:tags[0].start()] + '  <script src="game.js?v=%s"></script>\n' % ver + html[tags[-1].end():])
    out = out.replace(CSS_LINK, 'href="style.css?v=%s"' % ver)
    out = out.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="build" content="%s %s">' % (ver, stamp), 1)

    DIST.mkdir(exist_ok=True)
    files = {'index.html': out, 'game.js': js, 'style.css': css}
    for name, text in files.items():
        (DIST / name).write_text(text, 'utf-8')

    # the bundle is one script now, so a syntax slip anywhere would stop the whole game
    if pathlib.Path(JSC).exists():
        r = subprocess.run([JSC, '-e', "checkSyntax('dist/game.js')"], cwd=ROOT, capture_output=True, text=True)
        if r.returncode:
            fail('dist/game.js does not parse:\n' + r.stdout + r.stderr)

    with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in files:
            z.write(DIST / name, name)

    SINGLE.write_text(single_file(out, js, css, ver), 'utf-8')

    print('✓ build %s — %d scripts → dist/game.js (%d KB), zip %d KB'
          % (ver, len(tags), len(js.encode('utf-8')) // 1024, ZIP.stat().st_size // 1024))
    print('  cosmic-ascension.html (%d KB) → one file to send to a friend' % (SINGLE.stat().st_size // 1024))
    print('  dist/ → any static host (Netlify Drop, GitHub Pages); cosmic-ascension.zip → itch.io (HTML game)')


if __name__ == '__main__':
    main()
